//! The AAC decoder: `raw_data_block` / `er_raw_data_block` → channel elements →
//! spectral tools → synthesis → PCM (ISO 14496-3 §4.4 / §4.6).
//!
//! Coverage: AAC Main (backward-adaptive prediction), LC, SSR (gain control
//! parsed and ignored, as every practical decoder does), LTP; the 960-sample
//! frame variant; ER AAC-LC/LTP, ER AAC-LD (512/480) and ER AAC-ELD (low-delay
//! filterbank); every channel configuration 1-7 and 11-14 plus PCE-described
//! programs; coupling channel elements (dependent before/after TNS and
//! independent after IMDCT); PNS, intensity and M/S stereo, pulses, TNS.
//! HE-AAC (SBR/PS) is layered on top in [`crate::sbr`].
//!
//! Output order and element routing follow FFmpeg's model (see [`layout`]) so a
//! multichannel stream comes out in the same channel order, and noise bands are
//! generated by the same LCG, which is what lets the conformance census compare
//! sample-for-sample.

pub(crate) mod channel;
pub mod layout;
mod synth;
pub(crate) mod tools;

pub(crate) use channel::TNS_MAX_LONG;

